"""Render submission tables directly from complete, audited benchmark reports."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[2]
RESULTS = Path(__file__).resolve().parent / 'results'
OUT = ROOT / 'paper/appendix_tables'

def main():
    report = json.loads((RESULTS / 'summary.json').read_text())
    audit = json.loads((RESULTS / 'audit.json').read_text())
    assert report['status'] == 'complete' and audit['status'] == 'passed'
    rows = {(r['family'], r['method'], r['interval']): r for r in report['metrics']}
    # Exploratory simple baselines, added after the fixed comparisons.
    baselines = json.loads((ROOT / 'research/simple_baselines/results.json').read_text())
    assert baselines['status'] == 'complete'
    rows.update({(r['family'], r['method'], r['interval']): r for r in baselines['independent']['metrics'] if r['method'] != 'plugin'})
    get = lambda family, method, interval='adaptive': rows[(family, method, interval)]
    header = '% Generated by research/query_bench_20261104/render_tables.py.\n'
    table = [header, r'\begin{tabular}{@{}lrrrrr@{}}', r'\toprule',
             r'& \multicolumn{2}{c}{MSE / plug-in} & & & \\',
             r'Method / interval & all & same & Coverage & Width & Score \\', r'\midrule']
    for name, method, interval in [
        ('Plug-in / constant', 'plugin', 'constant'),
        ('Global rescale / constant', 'global_rescale', 'constant'),
        (r'No-image mean$^\dagger$ / constant', 'no_image', 'constant'),
        (r'Plug-in + constant$^\dagger$ / constant', 'constant', 'constant'),
        (r'Stain-context ridge$^\dagger$ / constant', 'ridge', 'constant'),
        ('Direct / adaptive', 'direct', 'adaptive'),
        (r'\method{} / adaptive', 'ligature', 'adaptive'),
        (r'\method{} / constant', 'ligature', 'constant')]:
        a = get('all_scored', method, interval)
        c = get('clustering', method, interval)
        table.append(f"{name} & {a['MSE_ratio']:.2f} & {c['MSE_ratio']:.2f} & {100*a['coverage']:.1f}\\% & {a['width']:.2f} & {a['interval_score']:.2f} " + r'\\')
    table += [r'\bottomrule', r'\end{tabular}']
    (OUT / 'query_forecasts.tex').write_text('\n'.join(table)+'\n')
    table = [header, r'\begin{tabular}{@{}lrrr@{}}', r'\toprule',
             r'Method & Moran $I$ & Geary $C$ & Log-assay contrast \\', r'\midrule']
    for name, method, interval in [
        ('Plug-in', 'plugin', 'constant'),
        (r'No-image training mean$^\dagger$', 'no_image', 'constant'),
        (r'Plug-in + constant$^\dagger$', 'constant', 'constant'),
        ('Selection affine', 'affine', 'constant'),
        ('Frozen-feature ridge (adapted)', 'ridge', 'constant'),
        ('Direct graph (adapted)', 'direct', 'adaptive'),
        ('Frozen direct-moment reuse', 'direct_moments', 'constant'),
        ('Independent Gaussian cells', 'independent_gaussian', 'adaptive'),
        ('Exact independent cell marginals', 'independent_marginals', 'adaptive'),
        (r'\method{} moment ratios', 'joint_moments', 'constant'),
        (r'\method{} joint samples', 'ligature', 'adaptive')]:
        values = [get(f, method, interval)['MSE_ratio'] for f in ['Moran','Geary','log_assay_clustering']]
        table.append(name + ' & ' + ' & '.join(f'{x:.3f}' for x in values) + r' \\')
    table += [r'\bottomrule', r'\end{tabular}']
    (OUT / 'query_transfer.tex').write_text('\n'.join(table)+'\n')
    # Full interval controls for every reported query family; keep negative results.
    table = [header, r'\begin{longtable}{@{}llrrr@{}}', r'\toprule',
             r'Family & Method / interval & Coverage & Width & Score \\', r'\midrule\endhead']
    for label, family in [('All 136','all_scored'), ('Clustering','clustering'), ('Cross-marker','cross'),
                           ('Moran $I$','Moran'), ('Geary $C$','Geary'), ('Log-assay','log_assay_clustering')]:
        methods = ['direct','ligature'] + (['ligature_analytic'] if family in ['all_scored','clustering','cross'] else [])
        for method in methods:
            for mode in ['raw','adaptive','constant']:
                a=get(family,method,mode)
                name={'direct':'Direct','ligature':r'\method{}','ligature_analytic':r'\method{} analytic'}[method]
                table.append(f"{label} & {name} / {mode} & {100*a['coverage']:.1f}\\% & {a['width']:.2f} & {a['interval_score']:.2f} " + r'\\')
        post_hoc = [('no_image', r'No-image mean$^\dagger$'), ('constant', r'Plug-in + constant$^\dagger$')]
        if family in ['all_scored', 'clustering', 'cross']:
            post_hoc.append(('ridge', r'Stain-context ridge$^\dagger$'))
        for method, name in post_hoc:
            a = get(family, method, 'constant')
            table.append(f"{label} & {name} / constant & {100*a['coverage']:.1f}\\% & {a['width']:.2f} & {a['interval_score']:.2f} " + r'\\')
    table += [r'\bottomrule', r'\end{longtable}']
    (OUT / 'query_interval_controls.tex').write_text('\n'.join(table)+'\n')
    if (RESULTS / 'he_summary.json').exists():
        he = json.loads((RESULTS / 'he_summary.json').read_text())
        assert he['status'] == 'complete' and he['folds'] == 5 and he['patients'] == 40
        hr = {(r['family'], r['method']): r for r in he['metrics']}
        table = [header, r'\begin{tabular}{@{}lrrrrr@{}}', r'\toprule',
                 r'& \multicolumn{2}{c}{MSE / own plug-in} & & & \\',
                 r'Method / interval & all & same & Coverage & Width & Score \\', r'\midrule']
        for name, method in [('Plug-in / constant', 'plugin_conformal'),
                             ('Direct / adaptive', 'direct_adaptive'),
                             ('Direct / constant', 'direct_constant'),
                             (r'\method{} / adaptive', 'ligature_conformal'),
                             (r'\method{} / constant', 'ligature_constant_scale_conformal')]:
            a = hr[('all136', method)]; c = hr[('clustering16', method)]
            table.append(f"{name} & {a['mse_relative_to_matched_plugin']:.3f} & {c['mse_relative_to_matched_plugin']:.3f} & {100*a['coverage']:.1f}\\% & {a['mean_width_normalized']:.2f} & {a['mean_interval_score_normalized']:.2f} " + r'\\')
        table += [r'\bottomrule', r'\end{tabular}']
        (OUT / 'he_geometry.tex').write_text('\n'.join(table)+'\n')

if __name__ == '__main__':
    main()
