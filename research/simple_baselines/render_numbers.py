"""Write paper/baseline_numbers.tex from results.json, so manuscript numbers stay generated."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
R = json.loads((HERE / 'results.json').read_text())
assert R['status'] == 'complete'
I = R['independent']
C = I['comparisons']
row = {(m['family'], m['method']): m for m in I['metrics']}
macros = {}


def num(name, value, digits=2):
    macros[name] = f'{value:.{digits}f}'


def signed(name, value, digits=0):
    text = f'{value:+.{digits}f}'
    macros[name] = '0' if float(text) == 0 else text


def interval(name, c, digits=2):
    num(name, c['diff'], digits)
    num(name + 'Lo', c['lo'], digits)
    num(name + 'Hi', c['hi'], digits)


# Reference run and lung: one shift per statistic, fitted on validation patients.
for tag, source in [('Ref', R['reference']), ('Lung', R['lung'])]:
    k = source['constant']
    num(f'Base{tag}ConstAll', k['MSE_all'])
    num(f'Base{tag}ConstCross', k['MSE_cross'])
    num(f'Base{tag}ConstSame', k['MSE_same'])
    num(f'Base{tag}ConstRho', k['rho_all'])
    signed(f'Base{tag}ConstBiasAll', k['bias_all'])
    signed(f'Base{tag}ConstBiasSame', k['bias_same'])
    interval(f'Base{tag}DiffAll', source['ligature_minus_constant_mse']['all_scored'])
    interval(f'Base{tag}DiffSame', source['ligature_minus_constant_mse']['clustering'])
macros['BaseRefDiffSameHi'] = f"{R['reference']['ligature_minus_constant_mse']['clustering']['hi']:.3f}"
num('BaseRefLigRho', R['reference']['ligature']['rho_all'])

# Independent calibration: interval scores.
num('BaseNoImageScore', row[('all_scored', 'no_image')]['interval_score'])
num('BaseConstScore', row[('all_scored', 'constant')]['interval_score'])
num('BaseConstSameScore', row[('clustering', 'constant')]['interval_score'])
num('BaseRidgeScore', row[('all_scored', 'ridge')]['interval_score'])
num('BaseRidgeAll', row[('all_scored', 'ridge')]['MSE_ratio'])
num('BaseRidgeSame', row[('clustering', 'ridge')]['MSE_ratio'])
num('BaseConstAll', row[('all_scored', 'constant')]['MSE_ratio'])
num('BaseConstSame', row[('clustering', 'constant')]['MSE_ratio'])
interval('BaseLigConstScore', C['ligature_adaptive_minus_constant_score_all_scored'])
interval('BaseLigConstSameScore', C['ligature_adaptive_minus_constant_score_clustering'])
interval('BaseDirConstScore', C['direct_adaptive_minus_constant_score_all_scored'])
interval('BaseLigRidgeScore', C['ligature_adaptive_minus_ridge_score_all_scored'])
interval('BaseLigRidgeSameScore', C['ligature_adaptive_minus_ridge_score_clustering'])
interval('BaseLigConstMSE', C['ligature_minus_constant_mse_all_scored'])
interval('BaseLigConstSameMSE', C['ligature_minus_constant_mse_clustering'])
interval('BaseLigRidgeMSE', C['ligature_minus_ridge_mse_all_scored'])
interval('BaseLigRidgeSameMSE', C['ligature_minus_ridge_mse_clustering'])

# The stronger in-sample constant, reported so the weaker variant is not the only one shown.
num('BaseInsampleAll', row[('all_scored', 'constant_insample')]['MSE_ratio'])
num('BaseInsampleSame', row[('clustering', 'constant_insample')]['MSE_ratio'])
num('BaseInsampleScore', row[('all_scored', 'constant_insample')]['interval_score'])
interval('BaseLigInsampleScore', C['ligature_adaptive_minus_constant_insample_score_all_scored'])
num('BaseSelectionAll', row[('all_scored', 'constant_selection')]['MSE_ratio'])

# Ridge penalty sensitivity. Fixed penalties are a post hoc sensitivity check, not a selection.
grid = I['ridge_penalty_sensitivity']
stable = [g for g in grid if 10 <= g['penalty'] <= 1e4]
num('BaseFixedAllLo', min(g['MSE_all'] for g in stable))
num('BaseFixedAllHi', max(g['MSE_all'] for g in stable))
num('BaseFixedSameLo', min(g['MSE_same'] for g in stable))
num('BaseFixedSameHi', max(g['MSE_same'] for g in stable))
num('BaseFixedMinScore', min(g['score_all'] for g in grid))
num('BaseFixedWorstAll', max(g['MSE_all'] for g in grid))
num('BaseFixedMinSameScore', min(g['score_same'] for g in grid))
interval('BaseLigFixedScore', I['ligature_minus_best_fixed_ridge_score'])

# Moran and Geary.
for family, tag in [('Moran', 'Moran'), ('Geary', 'Geary')]:
    num(f'Base{tag}NoImage', row[(family, 'no_image')]['MSE_ratio'])
    num(f'Base{tag}Const', row[(family, 'constant')]['MSE_ratio'])
    num(f'Base{tag}NoImageScore', row[(family, 'no_image')]['interval_score'])
    num(f'Base{tag}ConstScore', row[(family, 'constant')]['interval_score'])

# Bias under independent calibration.
for method, tag in [('direct', 'Direct'), ('ligature', 'Lig'), ('constant', 'Const'), ('ridge', 'Ridge')]:
    signed(f'BaseInd{tag}Bias', I['point'][method]['bias_all'])
    signed(f'BaseInd{tag}BiasSame', I['point'][method]['bias_same'])

lines = ['% Generated by research/simple_baselines/render_numbers.py; do not hand-edit.']
lines += [rf'\newcommand{{\{k}}}{{{v}}}' for k, v in macros.items()]
(ROOT / 'paper/baseline_numbers.tex').write_text('\n'.join(lines) + '\n')
print(len(macros), 'macros')
